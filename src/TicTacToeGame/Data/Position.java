package TicTacToeGame.Data;

public class Position {
    final int row;
    final int col;

    public Position(int row, int col) {
        this.row = row;
        this.col = col;
    }

    public int getRow() {
        return row;
    }

    public int getCol() {
        return col;
    }

    //getter & setters
}
